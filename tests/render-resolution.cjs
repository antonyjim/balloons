const { test } = require('node:test')
const assert = require('node:assert/strict')
const { RenderResolution } = require('../dist-ts/renderResolution')
test('normal frames preserve full quality and sustained slow frames reduce pixels', () => {
    const resolution = new RenderResolution()
    for (let i = 0; i < 600; i++) assert.equal(resolution.sample(1000 / 60), false)
    assert.equal(resolution.cap, 2)
    for (let i = 0; i < 89; i++) assert.equal(resolution.sample(1000 / 30), false)
    assert.equal(resolution.sample(1000 / 30), true)
    assert.equal(resolution.cap, 1.75)
    for (let i = 0; i < 900; i++) resolution.sample(1000 / 30)
    assert.equal(resolution.cap, 1)
})
test('resume gaps do not downgrade quality and recovery waits for sustained smooth frames', () => {
    const resolution = new RenderResolution()
    for (let i = 0; i < 89; i++) resolution.sample(50)
    assert.equal(resolution.sample(5000), false)
    assert.equal(resolution.cap, 2)
    for (let i = 0; i < 90; i++) resolution.sample(50)
    assert.equal(resolution.cap, 1.75)
    for (let i = 0; i < 599; i++) assert.equal(resolution.sample(1000 / 60), false)
    assert.equal(resolution.sample(1000 / 60), true)
    assert.equal(resolution.cap, 2)
    assert.equal(resolution.sample(NaN), false)
})
