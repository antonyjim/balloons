const { test } = require('node:test')
const assert = require('node:assert/strict')
const { ActivityLog, INACTIVITY_MS } = require('../dist-ts/activityLog')

test('five minutes idle ends the activity at the last input and removes the entire idle interval', () => {
    const log = new ActivityLog()
    log.rename('Alex', 0)
    log.input(1000)
    log.input(61000)
    assert.equal(log.tick(61000 + INACTIVITY_MS - 1), false)
    assert.equal(log.tick(61000 + INACTIVITY_MS), true)
    assert.equal(log.current, null)
    assert.equal(log.events.at(-1).at, 61000)
    assert.equal(log.events.at(-1).duration, 60000)
    assert.equal(log.totals(900000).balloons, 60000)
    log.input(1000000)
    assert.equal(log.current.start, 1000000)
})

test('switches and participant names separate time and puzzle audit events', () => {
    const log = new ActivityLog()
    log.rename('Alex', 0)
    log.input(0); log.view('sketchpad', 60000)
    log.input(70000); log.view('puzzle', 100000)
    log.input(110000); log.puzzle('activity', 'Garden (3 x 3)', false, 110000, 'round-1')
    log.input(120000); log.puzzle('activity', 'Garden (3 x 3)', false, 120000, 'round-1')
    log.input(130000); log.puzzle('solve', 'Garden (3 x 3)', true, 130000, 'round-1')
    log.rename('Sam', 140000)
    log.input(150000); log.end(160000, 'switched activity')
    assert.deepEqual(log.totals(160000), { balloons: 60000, sketchpad: 30000, matching: 0, puzzle: 40000 })
    assert.equal(log.totals(160000, 'Alex').puzzle, 30000)
    assert.equal(log.totals(160000, 'Sam').puzzle, 10000)
    assert.equal(log.events.find(e => e.kind === 'activity').solved, true)
    assert.equal(log.events.filter(e => e.kind === 'activity').length, 1)
})

test('no interaction means no tracked time; late switches cannot reintroduce the five-minute gap', () => {
    const log = new ActivityLog()
    log.view('puzzle', 0)
    assert.equal(log.totals(900000).puzzle, 0)
    log.input(900000); log.input(910000)
    log.view('sketchpad', 910000 + INACTIVITY_MS)
    assert.equal(log.totals(2000000).puzzle, 10000)
})
