const { test } = require('node:test')
const assert = require('node:assert/strict')
const { MatchingGame, SYMBOLS } = require('../dist-ts/matching/game')
test('each shelf collection has the entire alphabet and digits in order', () => {
    for (let i = 0; i < 30; i++) {
        const game = new MatchingGame()
        assert.equal(game.symbols.join(''), SYMBOLS)
        assert.equal(game.symbols.length, 36)
        assert.equal(new Set(game.symbols).size, 36)
        assert.equal(game.symbols.filter(symbol => /[A-Z]/.test(symbol)).length, 26)
        assert.equal(game.symbols.filter(symbol => /[0-9]/.test(symbol)).length, 10)
        assert.ok(game.symbols.every(symbol => SYMBOLS.includes(symbol)))
    }
})
test('only the dispensed shape can match, and it must be placed before dispensing another', () => {
    const game = new MatchingGame(() => 0.4)
    assert.equal(game.place(game.symbols[0]), false)
    const pending = game.dispense()
    assert.equal(game.dispense(), pending)
    assert.equal(game.place(game.symbols.find(symbol => symbol !== pending)), false)
    assert.equal(game.pending, pending)
    assert.equal(game.place(pending), true)
    assert.equal(game.pending, null)
    assert.equal(game.place(pending), false)
    assert.notEqual(game.dispense(), pending)
})
test('completing all shelves starts a fresh collection on the next button press', () => {
    const game = new MatchingGame()
    for (let i = 0; i < 36; i++) assert.equal(game.place(game.dispense()), true)
    assert.equal(game.matched.size, 36)
    assert.equal(game.pending, null)
    assert.ok(game.dispense())
    assert.equal(game.matched.size, 0)
    assert.equal(game.symbols.length, 36)
})
