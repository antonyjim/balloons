const { test } = require('node:test')
const assert = require('node:assert/strict')
const { parseGenerationSettings, weightedFinish } = require('../dist-ts/generationSettings')

test('generation weights combine foil and latex without losing zero exclusions', () => {
    const settings = parseGenerationSettings({ weights: { latex: 0, foil: 20, bubble: 80, paint: 0, apple: 0, duck: 0, watermelon: 0, 'hot-air': 0 }, showReset: false })
    assert.equal(weightedFinish(['latex', 'bubble', 'apple'], settings, 0), 'latex')
    assert.equal(weightedFinish(['latex', 'bubble', 'apple'], settings, .19), 'latex')
    assert.equal(weightedFinish(['latex', 'bubble', 'apple'], settings, .2), 'bubble')
    assert.equal(weightedFinish(['latex', 'bubble', 'apple'], settings, .999), 'bubble')
    assert.equal(settings.showReset, false)
})
test('invalid settings recover and an empty mix remains usable', () => {
    assert.equal(parseGenerationSettings(null).showReset, true)
    assert.equal(parseGenerationSettings({ weights: { foil: -1 } }).weights.foil, 18)
    const settings = parseGenerationSettings({ weights: Object.fromEntries(['latex', 'foil', 'bubble', 'paint', 'apple', 'duck', 'watermelon', 'hot-air'].map(type => [type, 0])) })
    assert.equal(weightedFinish(['latex', 'bubble'], settings), 'latex')
})

test('inflation settings recover older saves and reject unsafe values', () => {
    const defaults = parseGenerationSettings({ releaseOnFull: true })
    assert.equal(defaults.inflationSpeed, 1)
    assert.equal(defaults.minSize, null)
    assert.equal(defaults.maxSize, null)
    assert.equal(defaults.releaseOnFull, true)
    for (const value of [0, -1, Infinity, '2', 10]) assert.equal(parseGenerationSettings({ inflationSpeed: value }).inflationSpeed, 1)
    const settings = parseGenerationSettings({ inflationSpeed: 2, minSize: 120, maxSize: 80, releaseOnFull: true })
    assert.equal(settings.minSize, 80)
    assert.equal(settings.maxSize, 80)
    assert.equal(parseGenerationSettings(JSON.parse(JSON.stringify(settings))).inflationSpeed, 2)
    assert.equal(parseGenerationSettings({ minSize: -10, maxSize: 5000 }).maxSize, null)
})
test('speed and diameter controls respect device defaults and viewport limits', () => {
    const { generationConfig } = require('../dist-ts/generationSettings')
    const { maximumRadius } = require('../dist-ts/objects/sizeLimits')
    const base = { initialRadius: 35, minRadius: 24, maxRadius: 190, growthRate: 80, maxScreenRatio: .5, maxRadiusScreenRatio: .27 }
    const config = generationConfig(base, parseGenerationSettings({ inflationSpeed: 2, minSize: 60, maxSize: 240 }))
    assert.equal(config.growthRate, 160)
    assert.equal(config.initialRadius, 30)
    assert.equal(config.minRadius, 30)
    assert.equal(config.maxRadius, 120)
    assert.equal(maximumRadius(1000, 800, config), 120)
    assert.ok(maximumRadius(200, 200, config) <= 54, 'small screens still cap configured sizes')
    const reset = generationConfig(base, parseGenerationSettings(null))
    assert.equal(reset.growthRate, 80)
    assert.equal(reset.minRadius, 24)
    assert.equal(reset.maxRadius, 190)
    assert.equal(base.growthRate, 80, 'settings never modify the original device defaults')
})
